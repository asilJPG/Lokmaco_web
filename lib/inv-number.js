/**
 * Разбор инвентарного номера.
 *
 * Партия из N штук разворачивается в карточки `EQ-00690-01 … EQ-00690-20`,
 * и по базе `EQ-00690` они собираются обратно в одну строку списка.
 *
 * Наивное `replace(/-\d+$/, "")` тут не работает: у обычной позиции `EQ-00690`
 * оно съедало номер целиком и превращало её в `EQ`. Из-за этого все позиции
 * схлопывались в одну «партию», а сверка с iiko считала, что в базе нет ничего.
 *
 * Считать третий сегмент суффиксом экземпляра — тоже мало. У заведённых руками
 * номер трёхсегментный от рождения (`INV-1-5375`, `INV-INV-2147`), и они
 * попадали под то же правило: разные предметы слипались в одну партию, а
 * разбивка на экземпляры отказывала. Поэтому суффикс распознаётся по форме:
 * **2–3 цифры**, как их печатает `unitInvNumber`. Случайные четырёхзначные
 * хвосты ручных номеров под это не подходят.
 *
 * ⚠️ База общая с v2 (`web_lokmaco_v2/lib/inv-number.ts`) — правила разбора
 * обязаны совпадать дословно, иначе один и тот же номер два сайта прочитают
 * по-разному.
 */

/** Номер экземпляра в партии или null, если это не суффикс экземпляра. */
export function unitSuffix(inv) {
  const parts = String(inv || "").trim().split("-");
  if (parts.length < 3) return null;
  const last = parts[parts.length - 1];
  if (!/^\d{2,3}$/.test(last)) return null;
  return parseInt(last, 10);
}

export function baseInvNumber(inv) {
  const s = String(inv || "").trim();
  if (unitSuffix(s) === null) return s;
  return s.split("-").slice(0, -1).join("-");
}

/** Номер конкретного экземпляра партии: EQ-00690 + 7 из 20 -> EQ-00690-07 */
export function unitInvNumber(baseInv, index, total) {
  const width = Math.max(2, String(total).length);
  return `${baseInv}-${String(index).padStart(width, "0")}`;
}
