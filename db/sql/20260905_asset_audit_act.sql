-- Акт инвентаризации ОС: дата документа, кто проводит, излишки.
--
-- До этого обход знал только «начал такой-то тогда-то» и «нашли / не нашли».
-- Настоящий акт (как в iiko) требует ещё трёх вещей:
--   act_date     — дата документа. Обход часто закрывают на следующий день,
--                  а в акте должна стоять дата инвентаризации, а не закрытия;
--   performed_by — кто проводит. Это не всегда тот, кто нажал кнопку в
--                  телефоне: обходит кладовщик, отвечает МОЛ;
--   surplus      — излишки: нашли то, чего в этом месте числиться не должно.
--                  Без них акт односторонний — только недостача.
--
-- Таблица наша, легаси о ней не знает: старый сайт с asset_audits не работает.
ALTER TABLE asset_audits
  ADD COLUMN IF NOT EXISTS act_date date,
  ADD COLUMN IF NOT EXISTS performed_by text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS surplus jsonb NOT NULL DEFAULT '[]'::jsonb;
